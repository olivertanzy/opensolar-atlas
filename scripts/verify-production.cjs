// Exercise the actual distribution under a Pages-style path, without remote assets.
const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'../dist'),output=path.resolve(__dirname,'../test-results');
const prefix='/opensolar-atlas/';
const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.svg':'image/svg+xml','.png':'image/png','.jpg':'image/jpeg'};
async function main(){
 assert(fs.existsSync(path.join(root,'index.html')),'Run npm run build first');
 fs.mkdirSync(output,{recursive:true});
 const server=http.createServer((req,res)=>{
  const pathname=decodeURIComponent(new URL(req.url,'http://localhost').pathname);
  if(!pathname.startsWith(prefix)){res.writeHead(404);res.end();return;}
  const file=path.resolve(root,pathname.slice(prefix.length)||'index.html');
  if(!file.startsWith(root+path.sep)||!fs.existsSync(file)||!fs.statSync(file).isFile()){res.writeHead(404);res.end();return;}
  res.writeHead(200,{'Content-Type':mime[path.extname(file)]||'text/plain'});fs.createReadStream(file).pipe(res);
 });
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 let browser;
 const errors=[],external=[];
 try{
  browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||undefined,headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:960}});
  const origin=`http://127.0.0.1:${server.address().port}`,base=origin+prefix;
  await page.route('**/*',route=>{const url=route.request().url();if(url.startsWith(origin)||url.startsWith('data:'))return route.continue();external.push(url);return route.abort();});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('response',response=>{if(response.status()>=400)errors.push(`${response.status()}: ${response.url()}`);});
  await page.addInitScript(()=>localStorage.setItem('opensolar.imagery','off'));
  await page.goto(base,{waitUntil:'networkidle'});
  await page.waitForSelector('.model-card');
  await page.waitForFunction(()=>{const image=document.querySelector('.model-art img');return image?.complete&&image.naturalWidth>0;});
  await page.screenshot({path:path.join(output,'production-library-en.png')});
  await page.selectOption('#language','zh-CN');
  await page.screenshot({path:path.join(output,'production-library-zh.png')});
  await page.click('#guideLink');
  assert.match(await page.locator('#fullGuide').getAttribute('href'),/ADDING_A_MODEL\.zh-CN\.html$/,'Contributor guide must open a rendered UTF-8 document, not raw Markdown');
  const [documentPage]=await Promise.all([page.waitForEvent('popup'),page.click('#fullGuide')]);
  await documentPage.waitForLoadState('domcontentloaded');
  assert.equal(await documentPage.evaluate(()=>document.characterSet),'UTF-8');
  assert.equal(await documentPage.locator('article h1').textContent(),'如何新增一个 3D 主题模块');
  assert.equal(await documentPage.locator('article table').count(),2);
  assert(await documentPage.locator('pre code').count()>=4);
  assert.equal(await documentPage.locator('article ModelWorkbench').count(),0,'Vue examples must remain escaped code');
  assert(!(await documentPage.locator('article').textContent()).includes('\uFFFD'));
  await documentPage.screenshot({path:path.join(output,'documentation-zh-desktop.png')});
  await documentPage.setViewportSize({width:390,height:844});
  assert.equal(await documentPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await documentPage.screenshot({path:path.join(output,'documentation-zh-mobile.png')});
  await documentPage.locator('article a').filter({hasText:'English'}).click();
  assert.equal(await documentPage.locator('article h1').textContent(),'Add a 3D subject module');
  await documentPage.locator('article a').filter({hasText:'Architecture'}).click();
  assert.equal(await documentPage.locator('article h1').textContent(),'Vue and native Three.js architecture');
  await documentPage.goto(base+'docs/ADDING_A_MODEL.zh-CN.md');
  assert.equal(await documentPage.evaluate(()=>document.characterSet),'UTF-8','Old Markdown links must not show mojibake');
  assert((await documentPage.locator('body').textContent()).includes('如何新增一个 3D 主题模块'));
  await documentPage.close();
  assert.equal((await page.request.get(base+'docs/ADDING_A_MODEL.zh-CN.md')).status(),200);
  assert.equal((await page.request.get(base+'docs/ADDING_A_MODEL.md')).status(),200);
  await page.screenshot({path:path.join(output,'production-guide.png')});
  await page.click('#libraryLink');await page.selectOption('#language','en');
  assert.equal(await page.evaluate(()=>typeof window.SOLAR_DATA),'undefined','Library must not load the solar catalogue');
  await page.locator('[data-model="solar-system"] .primary-link').click();
  await page.waitForSelector('#scene canvas');
  assert.equal(await page.locator('html').getAttribute('lang'),'en');
  assert.equal(await page.evaluate(()=>typeof window.SOLAR_TEST),'undefined','No development driver in production');
  assert.equal(await page.evaluate(()=>typeof window.ATLAS_TEST),'undefined','No development lifecycle hook');
  await page.goto(base+'?lang=zh-CN&body=399',{waitUntil:'networkidle'});
  await page.waitForSelector('#scene canvas');
  assert.equal(await page.locator('#bodyDetails h1').textContent(),'地球');
  assert.match(await page.locator('.physical-metrics').innerText(),/6371\.0084/);
  await page.waitForSelector('#earthSearch');
  await page.fill('#earthSearch','北京');await page.locator('#earthResults button').first().click();
  await page.waitForFunction(()=>document.querySelector('#targetCaption').textContent.includes('北京'));
  assert.equal((await (await page.request.get(base+'data/earth/manifest.json')).json()).counts.cities,7342);
  await page.screenshot({path:path.join(output,'production-earth.png')});
  await page.selectOption('#language','en');
  await page.goto(base+'?lang=en&body=705',{waitUntil:'networkidle'});
  await page.waitForSelector('#scene canvas');
  assert.match(await page.locator('.profile-description').textContent(),/Miranda/);
  const source=await page.locator('.profile-intro a').getAttribute('href');
  assert.equal(new URL(source).hostname,'science.nasa.gov');
  await page.click('[data-tab="moons"]');await page.fill('#search','S/2009 S 1');
  await page.locator('#bodyList button').click();
  await page.waitForFunction(()=>document.querySelector('#bodyDetails h1').textContent.includes('2009'));
  assert.match(await page.locator('.discovery-metrics').innerText(),/2009/);
  await page.goto(base+'?lang=en&body=699',{waitUntil:'networkidle'});
  await page.waitForSelector('#scene canvas');
  await page.waitForTimeout(600);
  await page.screenshot({path:path.join(output,'production-saturn.png')});
  const response=await page.request.get(base+'data/horizons/699.json');
  assert.equal(response.status(),200,'Raw evidence remains accessible below the project path');
  await page.setViewportSize({width:390,height:844});
  await page.selectOption('#language','ko');await page.click('#detailsButton');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(output,'production-mobile.png')});
  await page.click('#libraryLink');await page.selectOption('#language','zh-CN');
  assert.equal(await page.locator('canvas').count(),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(output,'production-library-mobile.png')});
  assert.deepEqual(external,[],'Runtime assets must not need external requests');
  assert.deepEqual(errors,[]);
  const report={production:true,renderedUtf8Docs:true,documentLanguageAndArchitectureLinks:true,legacyMarkdownUtf8:true,pagesSubdirectory:true,earthGeography:true,defaultEnglish:true,localizedProfiles:true,physicalParameters:true,discoveryRecords:true,rawEvidence:true,mobileOverflow:false,externalRequests:external,errors};
  fs.writeFileSync(path.join(output,'production-verification.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
 }finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
